import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';

const root = process.cwd();
const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));

function detectCommit() {
  const envCandidates = [
    ['EDGEONE_COMMIT_SHA', process.env.EDGEONE_COMMIT_SHA],
    ['GITHUB_SHA', process.env.GITHUB_SHA],
    ['COMMIT_SHA', process.env.COMMIT_SHA]
  ];
  for (const [source, value] of envCandidates) {
    if (value) return { commit: String(value).slice(0, 12), source };
  }
  try {
    return {
      commit: execFileSync('git', ['-C', root, 'rev-parse', '--short=12', 'HEAD'], { encoding: 'utf8' }).trim(),
      source: 'git'
    };
  } catch (error) {
    return { commit: 'unknown', source: 'unknown' };
  }
}

const detected = detectCommit();
const buildInfo = {
  app: 'ai-habit-coach',
  version: pkg.version || '1.1.0',
  commit: detected.commit,
  builtAt: new Date().toISOString(),
  source: detected.source,
  environment: process.env.EDGEONE_ENV || process.env.NODE_ENV || 'production'
};
writeFileSync(path.join(root, 'version.json'), JSON.stringify(buildInfo, null, 2) + '\n', 'utf8');

const sourceFile = path.join(root, 'netlify', 'functions', 'api.js');
let source = readFileSync(sourceFile, 'utf8').replace(/\r\n/g, '\n');
source = source.replace("const crypto = require('crypto');\n", '');
source = source.replace("try { return require('../../version.json'); } catch (error) {}", 'try { return BUILD_INFO; } catch (error) {}');
source = source.replace("exports.handler = async function (event) {", "async function handleApiEvent(event) {");
source = source.replace('const MAX_IMAGE_CHARS = 8000000;', 'const MAX_IMAGE_CHARS = 5000000;');
source = source.replace('Netlify 服务端函数', 'EdgeOne Makers Cloud Function 服务端入口');
source = source.replace('所有模型密钥都保存在 Netlify\n * 环境变量中', '所有模型密钥都保存在 EdgeOne\n * 环境变量中');
source = source.replaceAll('process.env', 'runtimeEnv');
source = source.replace(/^'use strict';\n\n/, `'use strict';\n\n// Generated by edgeone-build.mjs. Do not edit manually.\nimport crypto from 'node:crypto';\nimport { installBlobQuotaStore } from './quota-store.js';\nconst BUILD_INFO = ${JSON.stringify(buildInfo)};\nglobalThis.__HABIT_BUILD_INFO__ = BUILD_INFO;\nlet runtimeEnv = {};\n\n`);

const tail = `

export async function onRequest(context) {
  runtimeEnv = context && context.env ? context.env : {};
  installBlobQuotaStore();
  const request = context && context.request ? context.request : null;
  if (!request) {
    return new Response(JSON.stringify({ ok: false, error: 'Cloud Function 请求对象缺失' }), {
      status: 500,
      headers: { 'Content-Type': 'application/json; charset=utf-8' }
    });
  }

  try {
    const headers = {};
    request.headers.forEach(function (value, key) { headers[key] = value; });
    if (context.clientIp && !headers['x-forwarded-for']) headers['x-forwarded-for'] = context.clientIp;
    const method = String(request.method || 'GET').toUpperCase();
    let body = '';
    if (method === 'POST' || method === 'PUT' || method === 'PATCH') body = await request.text();
    const result = await handleApiEvent({
      httpMethod: method,
      headers: headers,
      body: body,
      rawUrl: request.url,
      path: new URL(request.url).pathname
    });
    const status = result && result.statusCode ? result.statusCode : 200;
    const responseBody = status === 204 ? null : (result && result.body != null ? result.body : '');
    return new Response(responseBody, {
      status: status,
      headers: result && result.headers ? result.headers : {}
    });
  } catch (error) {
    console.error('Cloud Function error:', error);
    return new Response(JSON.stringify({
      ok: false,
      error: 'Cloud Function 内部错误: ' + (error && error.message ? error.message : '未知错误')
    }), {
      status: 500,
      headers: { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' }
    });
  }
}
`;
const generated = source.trimEnd() + tail;
writeFileSync(path.join(root, 'cloud-functions', 'api', '[[default]].js'), generated, 'utf8');
console.log(JSON.stringify({ ok: true, version: buildInfo.version, commit: buildInfo.commit, source: buildInfo.source }));
